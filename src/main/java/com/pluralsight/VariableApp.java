package com.pluralsight;

public class VariableApp {
    public static void main(String[] args) {
        String favColor = "Blue";
        String year = "2026";
        char middleNameI = 'M';
        boolean pets = true;
        String message = "With great power comes great responsibility.";

        System.out.println("My favorite color is: " + favColor);
        System.out.println("The year is: " + year);
        System.out.println("My middle initial name is: " + middleNameI);
        System.out.println("Do you have any pets?: " + pets);
        System.out.println(message);

    }
}
